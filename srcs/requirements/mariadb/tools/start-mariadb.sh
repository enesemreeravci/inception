#!/bin/sh

set -eu

DATADIR="/var/lib/mysql"
SOCKET="/run/mysqld/mysqld.sock"
MARKER="$DATADIR/.inception_initialized"

# Validate environment variables
: "${MYSQL_DATABASE:?MYSQL_DATABASE must be set}"
: "${MYSQL_USER:?MYSQL_USER must be set}"

# Validate database and username
case "$MYSQL_DATABASE" in
    ""|*[!a-zA-Z0-9_]*)
        echo "Error: Invalid database name" >&2
        exit 1
        ;;
esac

case "$MYSQL_USER" in
    ""|*[!a-zA-Z0-9_]*)
        echo "Error: Invalid database username" >&2
        exit 1
        ;;
esac

# Read passwords from Docker secrets
MYSQL_PASSWORD="$(cat /run/secrets/db_password)"
MYSQL_ROOT_PASSWORD="$(cat /run/secrets/db_root_password)"

# Validate passwords
[ -n "$MYSQL_PASSWORD" ] || {
    echo "Error: Database password is empty" >&2
    exit 1
}

[ -n "$MYSQL_ROOT_PASSWORD" ] || {
    echo "Error: Root password is empty" >&2
    exit 1
}

# Passwords generated by Makefile are hexadecimal
case "$MYSQL_PASSWORD:$MYSQL_ROOT_PASSWORD" in
    *[!a-fA-F0-9:]*)
        echo "Error: Database passwords must be hexadecimal" >&2
        exit 1
        ;;
esac

# Prepare directories
mkdir -p "$DATADIR" /run/mysqld
chown mysql:mysql "$DATADIR" /run/mysqld

# Initialize system tables on first installation
if [ ! -d "$DATADIR/mysql" ]; then
    echo "[MariaDB] Initializing system tables..."

    mariadb-install-db \
        --user=mysql \
        --datadir="$DATADIR" \
        --auth-root-authentication-method=socket \
        --skip-test-db
fi

# Configure database only when initialization is incomplete
if [ ! -f "$MARKER" ]; then
    echo "[MariaDB] Configuring WordPress database..."

    # Start temporary server without network access
    mariadbd \
        --user=mysql \
        --datadir="$DATADIR" \
        --skip-networking \
        --socket="$SOCKET" &

    TEMP_PID=$!

    # Wait for temporary server
    count=0

    until mariadb-admin \
        --protocol=socket \
        --socket="$SOCKET" \
        ping --silent >/dev/null 2>&1
    do
        count=$((count + 1))

        if [ "$count" -ge 30 ]; then
            echo "Error: MariaDB startup timeout" >&2
            exit 1
        fi

        if ! kill -0 "$TEMP_PID" 2>/dev/null; then
            echo "Error: MariaDB exited unexpectedly" >&2
            exit 1
        fi

        sleep 1
    done

    # Determine whether the root password was already set
    if mariadb \
        --protocol=socket \
        --socket="$SOCKET" \
        -u root \
        -e "SELECT 1" >/dev/null 2>&1
    then
        ROOT_AUTH="socket"
    elif MYSQL_PWD="$MYSQL_ROOT_PASSWORD" mariadb \
        --protocol=socket \
        --socket="$SOCKET" \
        -u root \
        -e "SELECT 1" >/dev/null 2>&1
    then
        ROOT_AUTH="password"
    else
        echo "Error: Cannot authenticate as MariaDB root" >&2
        exit 1
    fi

    # Helper for authenticated SQL commands
    run_sql() {
        if [ "$ROOT_AUTH" = "password" ]; then
            MYSQL_PWD="$MYSQL_ROOT_PASSWORD" mariadb \
                --protocol=socket \
                --socket="$SOCKET" \
                -u root
        else
            mariadb \
                --protocol=socket \
                --socket="$SOCKET" \
                -u root
        fi
    }

    # Create database and WordPress user
    run_sql <<SQL
CREATE DATABASE IF NOT EXISTS \`${MYSQL_DATABASE}\`
    CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE USER IF NOT EXISTS '${MYSQL_USER}'@'%'
    IDENTIFIED BY '${MYSQL_PASSWORD}';

ALTER USER '${MYSQL_USER}'@'%'
    IDENTIFIED BY '${MYSQL_PASSWORD}';

GRANT ALL PRIVILEGES ON \`${MYSQL_DATABASE}\`.*
    TO '${MYSQL_USER}'@'%';

ALTER USER 'root'@'localhost'
    IDENTIFIED BY '${MYSQL_ROOT_PASSWORD}';

FLUSH PRIVILEGES;
SQL

    # Shut down temporary server
    MYSQL_PWD="$MYSQL_ROOT_PASSWORD" mariadb-admin \
        --protocol=socket \
        --socket="$SOCKET" \
        -u root \
        shutdown

    wait "$TEMP_PID"

    # Mark completed initialization
    touch "$MARKER"
    chown mysql:mysql "$MARKER"

    echo "[MariaDB] Initialization completed."
fi

# Start MariaDB as the main container process
echo "[MariaDB] Starting MariaDB..."

exec mariadbd --user=mysql --datadir="$DATADIR"
